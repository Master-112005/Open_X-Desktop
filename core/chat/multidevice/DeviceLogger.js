/**
 * Privacy-safe desktop multi-device logger.
 */
class DeviceLogger {
  /** @param {object} _event Event. */
  debug(_event) {}

  /** @param {object} _event Event. */
  info(_event) {}

  /** @param {object} _event Event. */
  warn(_event) {}

  /** @param {object} _event Event. */
  error(_event) {}
}

module.exports = DeviceLogger;
